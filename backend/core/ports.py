"""Interfaces for everything that touches the outside world. Core logic depends on these, never on smtplib, imaplib,
Ollama or the wall clock directly, so tests can swap in the fakes from `backend.core.fakes`.

Real implementations (owned by the milestone that builds them):
  Mailer      -> backend.core.mailer.SmtpMailer       (milestone 4)
  ImapClient  -> backend.core.tracker.GmailImap       (milestone 5)
  LlmClient   -> backend.core.services.OllamaClient   (here, wraps backend.core.llm)
  PageCache   -> backend.core.store.CrawlStore
  Clock       -> backend.core.services.SystemClock
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Protocol, TypeVar

from pydantic import BaseModel

T = TypeVar("T", bound=BaseModel)


# ---------------------------------------------------------------- mail out
@dataclass(frozen=True)
class OutgoingEmail:
    from_addr: str
    from_name: str
    to_addr: str
    subject: str
    body: str  # plain text, footer already applied
    message_id: str  # generated by the sender BEFORE the SMTP call and stored in `messages.message_id`
    in_reply_to: str | None = None
    references: tuple[str, ...] = ()
    attachment_path: str | None = None


@dataclass(frozen=True)
class SendReceipt:
    smtp_result: str  # e.g. "250 2.0.0 OK"


class MailerError(Exception):
    """Base class. `outcome_unknown` is True when the server may have accepted the message (timeout after DATA,
    connection dropped): the sender then marks the message needs_confirmation instead of failed."""

    outcome_unknown = False


class SmtpAuthError(MailerError):
    """Login rejected. Stops the whole run immediately: never retried, never looped."""


class RecipientRejected(MailerError):
    """The server refused this recipient (5.x.x at RCPT). The message fails; the run continues."""


class TransientSendError(MailerError):
    """Network or 4.x.x trouble before the message was handed over. Safe to leave queued and retry later."""


class OutcomeUnknownError(MailerError):
    outcome_unknown = True


class Mailer(Protocol):
    def send(self, email: OutgoingEmail) -> SendReceipt: ...
    def check_login(self) -> None:
        """Raises SmtpAuthError / TransientSendError."""
    def close(self) -> None: ...


# ---------------------------------------------------------------- mail in
@dataclass(frozen=True)
class IncomingMessage:
    uid: int
    raw: bytes  # full RFC 822 message; parsed with the stdlib `email` package


@dataclass
class FetchResult:
    uidvalidity: int
    messages: list[IncomingMessage] = field(default_factory=list)


class ImapAuthError(Exception):
    pass


class ImapClient(Protocol):
    def fetch_new(self, folder: str, after_uid: int) -> FetchResult:
        """Messages with uid > after_uid, oldest first. Caller compares `uidvalidity` with the stored value."""
    def close(self) -> None: ...


# ---------------------------------------------------------------- llm
class LlmClient(Protocol):
    def generate_json(self, schema: type[T], system: str, user: str, *, model: str | None = None,
                      num_predict: int = 700) -> T:
        """Raises backend.core.llm.LlmError when the model is unreachable or returns unusable output."""


# ---------------------------------------------------------------- crawl cache
class PageCache(Protocol):
    def get_page(self, url: str): ...
    def put_page(self, url: str, final_url: str, status: int, content_type: str, html: str, tier: str,
                 etag: str | None = None, last_modified: str | None = None, ttl_s: int = ...) -> None: ...


# ---------------------------------------------------------------- time
class Clock(Protocol):
    def now(self) -> float:
        """Unix seconds."""
    def sleep(self, seconds: float) -> None: ...
