// Export the FastAPI OpenAPI schema and generate TypeScript types from it.
// Usage: npm run gen:api   (run `npm run gen:api -- --check` in CI to detect drift)
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..', '..')
const python = process.env.REACHOUT_PYTHON || join(root, '.venv', 'bin', 'python')
const outDir = resolve(here, '..', 'src', 'lib', 'api')
const schemaPath = join(outDir, 'openapi.json')
const typesPath = join(outDir, 'schema.d.ts')
const check = process.argv.includes('--check')

mkdirSync(outDir, { recursive: true })
execFileSync(python, ['-m', 'backend.api.export_openapi', schemaPath], {
  cwd: root,
  env: { ...process.env, PYTHONPATH: root },
  stdio: ['ignore', 'ignore', 'inherit'],
})

const ast = await openapiTS(new URL(`file://${schemaPath}`))
const banner = '// GENERATED by scripts/gen-api.mjs from the FastAPI OpenAPI schema. Do not edit.\n'
const next = banner + astToString(ast)

if (check) {
  let current = ''
  try { current = readFileSync(typesPath, 'utf8') } catch { /* missing */ }
  if (current !== next) {
    console.error('src/lib/api/schema.d.ts is out of date. Run: npm run gen:api')
    process.exit(1)
  }
  console.log('API types are up to date.')
} else {
  writeFileSync(typesPath, next)
  console.log(`wrote ${typesPath}`)
}
